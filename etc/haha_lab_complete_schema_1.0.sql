-- Trigger Function 1: Log schedule completion, no-show, and reschedule
-- Automatically creates history records when schedule status changes
CREATE OR REPLACE FUNCTION log_schedule_completion()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    duration_mins INT;
    start_dt TIMESTAMP;
    end_dt TIMESTAMP;
    start_fmt TEXT;
    end_fmt TEXT;
    now_fmt TEXT;
BEGIN
    -- Current time in Asia/Seoul timezone, formatted as YYYYMMDD HH:mm
    now_fmt := TO_CHAR(TIMEZONE('Asia/Seoul', NOW()), 'YYYYMMDD HH24:MI');
    
    -- ===== CASE 1: Session/Consultation Completed =====
    IF NEW.status = 'completed' AND OLD.status != 'completed' THEN
        -- Calculate duration in minutes
        start_dt := (NEW.date || ' ' || NEW.start_time)::TIMESTAMP;
        end_dt := (NEW.date || ' ' || NEW.end_time)::TIMESTAMP;
        duration_mins := EXTRACT(EPOCH FROM (end_dt - start_dt)) / 60;
        
        -- Format datetime as YYYYMMDD HH:mm
        start_fmt := REPLACE(NEW.date, '-', '') || ' ' || NEW.start_time;
        end_fmt := REPLACE(NEW.date, '-', '') || ' ' || NEW.end_time;
        
        -- Insert activity log
        INSERT INTO activity_logs (teacher_name, center_name, type, action, details)
        SELECT 
            t.name,
            t.center,
            CASE WHEN NEW.type = 'reserve' THEN '상담' ELSE '수업' END,
            CASE WHEN NEW.type = 'reserve' THEN '상담완료' ELSE '수업완료' END,
            NEW.client_name || ' (' || start_fmt || ' ~ ' || end_fmt || ')'
        FROM teachers t
        WHERE t.teacher_id = NEW.teacher_id;
        
        -- Insert history record
        INSERT INTO histories (
            teacher_id, client_id, client_name, 
            type, category, action, 
            event_datetime, start_datetime, end_datetime, duration_minutes, 
            details
        ) VALUES (
            NEW.teacher_id, 
            NEW.client_id, 
            NEW.client_name,
            CASE WHEN NEW.type = 'reserve' THEN 'consultation' ELSE 'session' END,
            CASE WHEN NEW.type = 'reserve' THEN 'consultation_history' ELSE 'session_history' END,
            CASE WHEN NEW.type = 'reserve' THEN '상담완료' ELSE '수업완료' END,
            now_fmt,
            start_fmt,
            end_fmt,
            duration_mins,
            '정상 완료됨'
        );
    END IF;
    
    -- ===== CASE 2: No-Show Marked =====
    IF NEW.status = 'noshow' AND OLD.status != 'noshow' THEN
        start_fmt := REPLACE(NEW.date, '-', '') || ' ' || NEW.start_time;
        
        INSERT INTO histories (
            teacher_id, client_id, client_name, 
            type, category, action, 
            event_datetime, start_datetime, noshow_datetime,
            details
        ) VALUES (
            NEW.teacher_id, 
            NEW.client_id, 
            NEW.client_name,
            'noshow',
            CASE WHEN NEW.type = 'reserve' THEN 'consultation_history' ELSE 'session_history' END,
            '미출석',
            now_fmt,
            start_fmt,
            now_fmt,
            '미출석 처리됨'
        );
    END IF;
    
    -- ===== CASE 3: Schedule Rescheduled =====
    IF (NEW.date != OLD.date OR NEW.start_time != OLD.start_time) 
       AND NEW.status != 'deleted' 
       AND OLD.status != 'deleted' THEN
        
        start_fmt := REPLACE(OLD.date, '-', '') || ' ' || OLD.start_time;
        end_fmt := REPLACE(NEW.date, '-', '') || ' ' || NEW.start_time;
        
        INSERT INTO histories (
            teacher_id, client_id, client_name, 
            type, category, action, 
            event_datetime, original_datetime, changed_datetime, reschedule_datetime,
            details
        ) VALUES (
            NEW.teacher_id, 
            NEW.client_id, 
            NEW.client_name,
            'reschedule',
            CASE WHEN NEW.type = 'reserve' THEN 'consultation_history' ELSE 'session_history' END,
            '일정변경',
            now_fmt,
            start_fmt,
            end_fmt,
            now_fmt,
            '일정이 변경됨'
        );
    END IF;
    
    RETURN NEW;
END;
$$;

COMMENT ON FUNCTION log_schedule_completion IS 'Automatically log history when schedule status changes (completed/noshow/rescheduled)';


-- Trigger Function 2: Log schedule deletion
-- Automatically creates history record when schedule is deleted
CREATE OR REPLACE FUNCTION log_schedule_deletion()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    start_fmt TEXT;
    now_fmt TEXT;
BEGIN
    -- Format datetime as YYYYMMDD HH:mm
    start_fmt := REPLACE(OLD.date, '-', '') || ' ' || OLD.start_time;
    now_fmt := TO_CHAR(TIMEZONE('Asia/Seoul', NOW()), 'YYYYMMDD HH24:MI');
    
    INSERT INTO histories (
        teacher_id, client_id, client_name, 
        type, category, action, 
        event_datetime, start_datetime, delete_datetime,
        details
    ) VALUES (
        OLD.teacher_id, 
        OLD.client_id, 
        OLD.client_name,
        'delete',
        CASE WHEN OLD.type = 'reserve' THEN 'consultation_history' ELSE 'session_history' END,
        '일정삭제',
        now_fmt,
        start_fmt,
        now_fmt,
        '스케줄이 삭제됨'
    );
    
    RETURN OLD;
END;
$$;

COMMENT ON FUNCTION log_schedule_deletion IS 'Automatically log history when schedule is deleted';


-- Trigger Function 3: Update notice timestamp
-- Automatically updates updated_at when notice is modified
CREATE OR REPLACE FUNCTION update_notice_timestamp()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at = TIMEZONE('utc', NOW());
    RETURN NEW;
END;
$$;

COMMENT ON FUNCTION update_notice_timestamp IS 'Automatically update updated_at timestamp when notice is modified';


