-- Function 1: Get schedules by date
-- Used by: index.html (calendar views)
CREATE OR REPLACE FUNCTION get_schedules_by_date(p_teacher_id TEXT, p_date TEXT)
RETURNS TABLE (
    id BIGINT,
    client_name TEXT,
    type TEXT,
    start_time TEXT,
    end_time TEXT,
    status TEXT
) 
LANGUAGE plpgsql
AS $$
BEGIN
    RETURN QUERY
    SELECT 
        s.id, 
        s.client_name, 
        s.type, 
        s.start_time, 
        s.end_time, 
        s.status
    FROM schedules s
    WHERE s.teacher_id = p_teacher_id 
    AND s.date = p_date
    AND s.status != 'deleted'
    ORDER BY s.start_time;
END;
$$;

COMMENT ON FUNCTION get_schedules_by_date IS 'Retrieve all schedules for a specific teacher and date';


-- Function 2: Get client statistics
-- Used by: index.html (dashboard statistics), admin.html (teacher detail)
CREATE OR REPLACE FUNCTION get_client_stats(p_teacher_id TEXT)
RETURNS TABLE (
    total_clients INT,
    active_clients INT,
    reserve_clients INT,
    paused_clients INT,
    terminated_clients INT
)
LANGUAGE plpgsql
AS $$
BEGIN
    RETURN QUERY
    SELECT 
        COUNT(*)::INT AS total_clients,
        COUNT(CASE WHEN type = 'client' AND status = 'active' THEN 1 END)::INT AS active_clients,
        COUNT(CASE WHEN type = 'reserve' AND status = 'active' THEN 1 END)::INT AS reserve_clients,
        COUNT(CASE WHEN status = 'paused' THEN 1 END)::INT AS paused_clients,
        COUNT(CASE WHEN status = 'terminated' THEN 1 END)::INT AS terminated_clients
    FROM clients
    WHERE teacher_id = p_teacher_id
    AND status != 'deleted';
END;
$$;

COMMENT ON FUNCTION get_client_stats IS 'Calculate client statistics by status for a teacher';


-- Function 3: Get session time statistics (weekly/monthly/total)
-- Used by: index.html (client detail page - session history tab statistics)
CREATE OR REPLACE FUNCTION get_session_time_stats(p_client_id TEXT)
RETURNS TABLE (
    weekly_minutes INT,
    monthly_minutes INT,
    total_minutes INT
)
LANGUAGE plpgsql
AS $$
DECLARE
    week_start TEXT;
    month_start TEXT;
BEGIN
    -- Get start of current week (Monday) in YYYYMMDD format
    week_start := TO_CHAR(DATE_TRUNC('week', CURRENT_DATE), 'YYYYMMDD');
    
    -- Get start of current month in YYYYMMDD format
    month_start := TO_CHAR(DATE_TRUNC('month', CURRENT_DATE), 'YYYYMMDD');
    
    RETURN QUERY
    SELECT 
        -- Weekly: sum of duration_minutes where start_datetime >= week_start
        COALESCE(SUM(CASE 
            WHEN SUBSTRING(start_datetime, 1, 8) >= week_start 
            THEN duration_minutes 
            ELSE 0 
        END), 0)::INT AS weekly_minutes,
        
        -- Monthly: sum of duration_minutes where start_datetime >= month_start
        COALESCE(SUM(CASE 
            WHEN SUBSTRING(start_datetime, 1, 8) >= month_start 
            THEN duration_minutes 
            ELSE 0 
        END), 0)::INT AS monthly_minutes,
        
        -- Total: sum of all duration_minutes
        COALESCE(SUM(duration_minutes), 0)::INT AS total_minutes
    FROM histories
    WHERE client_id = p_client_id
    AND category = 'session_history'
    AND action = '수업완료'
    AND start_datetime IS NOT NULL;
END;
$$;

COMMENT ON FUNCTION get_session_time_stats IS 'Calculate weekly, monthly, and total session minutes for a client';


