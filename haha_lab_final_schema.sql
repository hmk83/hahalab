-- ============================================================
-- [Safety Checks] 기존 테이블 구조 보정
-- (테이블이 이미 생성된 경우, 누락된 핵심 컬럼 추가)
-- ============================================================
DO $$
BEGIN
    -- teachers 테이블에 status 컬럼 없으면 추가
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name='teachers' AND column_name='status') THEN
        ALTER TABLE teachers ADD COLUMN status TEXT DEFAULT 'Active';
    END IF;
    
    -- notices 테이블에 is_hidden 컬럼 없으면 추가
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name='notices' AND column_name='is_hidden') THEN
        ALTER TABLE notices ADD COLUMN is_hidden BOOLEAN DEFAULT FALSE;
    END IF;
    
    -- play_contents 테이블에 is_hidden 컬럼 없으면 추가
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name='play_contents' AND column_name='is_hidden') THEN
        ALTER TABLE play_contents ADD COLUMN is_hidden BOOLEAN DEFAULT FALSE;
    END IF;
    
    -- schedules 테이블 status 기본값 확인
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name='schedules' AND column_name='status') THEN
        ALTER TABLE schedules ADD COLUMN status TEXT DEFAULT 'scheduled';
    END IF;
    
    -- clients 테이블 status 기본값 확인
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name='clients' AND column_name='status') THEN
        ALTER TABLE clients ADD COLUMN status TEXT DEFAULT 'active';
    END IF;
END $$;


