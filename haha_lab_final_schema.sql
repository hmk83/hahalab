-- 1. 선생님 (Teachers) 테이블
CREATE TABLE IF NOT EXISTS teachers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc', NOW()),
    teacher_id TEXT UNIQUE NOT NULL, -- 로그인 ID
    password TEXT NOT NULL,          -- 비밀번호 (실제 프로덕션에서는 해싱 필요)
    name TEXT NOT NULL,
    center TEXT,
    gender TEXT,
    age INT,
    contact TEXT,
    email TEXT,
    plan TEXT DEFAULT 'Basic Plan',  -- 'Basic Plan', 'Pro Plan', 'Enterprise'
    status TEXT DEFAULT 'Active',    -- 'Active', 'Paused', 'Suspended'
    memo TEXT,
    registered_clients INT DEFAULT 0
);

-- 2. 내담자 (Clients) 테이블
CREATE TABLE IF NOT EXISTS clients (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc', NOW()),
    teacher_id TEXT NOT NULL,        -- 담당 선생님 ID
    name TEXT NOT NULL,
    type TEXT NOT NULL,              -- 'client'(정규), 'reserve'(대기)
    status TEXT DEFAULT 'active',    -- 'active', 'paused', 'terminated', 'deleted'
    gender TEXT,
    dob TEXT,                        -- YYYY-MM-DD 형식
    age INT,
    contact TEXT,
    address TEXT,
    guardians JSONB,                 -- 보호자 정보 (JSON 배열)
    session_time INT DEFAULT 50,     -- 기본 수업 시간 (분)
    diagnosis TEXT,
    initial_consult TEXT,
    areas JSONB,                     -- 발달 영역 태그 정보 {lang:[], cogn:[], behv:[]}
    memo TEXT,
    reserve_date TEXT,               -- 상담 예약 날짜 (reserve 타입인 경우)
    reserve_time TEXT                -- 상담 예약 시간 (reserve 타입인 경우)
);

-- 3. 스케줄 (Schedules) 테이블
CREATE TABLE IF NOT EXISTS schedules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc', NOW()),
    teacher_id TEXT NOT NULL,
    client_id TEXT NOT NULL,
    client_name TEXT NOT NULL,
    type TEXT NOT NULL,              -- 'client'(수업), 'reserve'(상담)
    date TEXT NOT NULL,              -- YYYY-MM-DD 형식
    start_time TEXT NOT NULL,        -- HH:MM 형식
    end_time TEXT NOT NULL,          -- HH:MM 형식
    status TEXT DEFAULT 'scheduled', -- 'scheduled', 'completed', 'noshow', 'deleted', 'changed'
    memo TEXT
);

-- 4. 공지사항 (Notices) 테이블
CREATE TABLE IF NOT EXISTS notices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc', NOW()),
    type TEXT NOT NULL,              -- '일반', '업데이트', '점검', '이벤트'
    title TEXT NOT NULL,
    content TEXT,                    -- HTML 포함 가능
    date TEXT,                       -- 공지 날짜 (YYYY-MM-DD)
    is_hidden BOOLEAN DEFAULT FALSE
);

-- 5. Play Lab 콘텐츠 (Play Contents) 테이블
CREATE TABLE IF NOT EXISTS play_contents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc', NOW()),
    cat_id TEXT NOT NULL,            -- 'think', 'sound', 'listen', 'see', 'speak', 'life', 'art'
    title TEXT NOT NULL,
    url TEXT,
    tags TEXT[],                     -- PostgreSQL Array Type
    thumbnail TEXT,
    views INT DEFAULT 0,
    is_hidden BOOLEAN DEFAULT FALSE
);

-- 6. 활동 로그 (Activity Logs) 테이블
CREATE TABLE IF NOT EXISTS activity_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc', NOW()),
    teacher_name TEXT,
    center_name TEXT,
    type TEXT,                       -- '시스템', '수업', '학생관리', '상담'
    action TEXT,                     -- '로그인', '수업완료', '상담완료', '학생추가' 등
    details TEXT,
    occurred_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc', NOW())
);


