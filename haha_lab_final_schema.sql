-- 특정 날짜의 스케줄 조회 함수
CREATE OR REPLACE FUNCTION get_schedules_by_date(p_teacher_id TEXT, p_date TEXT)
RETURNS TABLE (
    id BIGINT,
    client_name TEXT,
    type TEXT,
    start_time TEXT,
    end_time TEXT,
    status TEXT
) AS $$
BEGIN
    RETURN QUERY
    SELECT s.id, s.client_name, s.type, s.start_time, s.end_time, s.status
    FROM schedules s
    WHERE s.teacher_id = p_teacher_id 
    AND s.date = p_date
    AND s.status != 'deleted'
    ORDER BY s.start_time;
END;
$$ LANGUAGE plpgsql;

-- 내담자 통계 조회 함수
CREATE OR REPLACE FUNCTION get_client_stats(p_teacher_id TEXT)
RETURNS TABLE (
    total_clients INT,
    active_clients INT,
    reserve_clients INT,
    paused_clients INT,
    terminated_clients INT
) AS $$
BEGIN
    RETURN QUERY
    SELECT 
        COUNT(*)::INT AS total_clients,
        COUNT(CASE WHEN type = 'client' AND status = 'active' THEN 1 END)::INT AS active_clients,
        COUNT(CASE WHEN type = 'reserve' AND status = 'active' THEN 1 END)::INT AS reserve_clients,
        COUNT(CASE WHEN status = 'paused' THEN 1 END)::INT AS paused_clients,
        COUNT(CASE WHEN status = 'terminated' THEN 1 END)::INT AS terminated_clients
    FROM clients
    WHERE teacher_id = p_teacher_id
    AND status != 'deleted';
END;
$$ LANGUAGE plpgsql;

-- 내담자 수업시간 통계 조회 함수 (주간/월간/총)
CREATE OR REPLACE FUNCTION get_session_time_stats(p_client_id TEXT)
RETURNS TABLE (
    weekly_minutes INT,
    monthly_minutes INT,
    total_minutes INT
) AS $$
DECLARE
    week_start TEXT;
    month_start TEXT;
BEGIN
    -- 이번 주 시작 (월요일)
    week_start := TO_CHAR(DATE_TRUNC('week', CURRENT_DATE), 'YYYYMMDD');
    -- 이번 달 시작
    month_start := TO_CHAR(DATE_TRUNC('month', CURRENT_DATE), 'YYYYMMDD');
    
    RETURN QUERY
    SELECT 
        COALESCE(SUM(CASE 
            WHEN SUBSTRING(start_datetime, 1, 8) >= week_start 
            THEN duration_minutes 
            ELSE 0 
        END), 0)::INT AS weekly_minutes,
        COALESCE(SUM(CASE 
            WHEN SUBSTRING(start_datetime, 1, 8) >= month_start 
            THEN duration_minutes 
            ELSE 0 
        END), 0)::INT AS monthly_minutes,
        COALESCE(SUM(duration_minutes), 0)::INT AS total_minutes
    FROM histories
    WHERE client_id = p_client_id
    AND category = 'session_history'
    AND action = '수업완료'
    AND start_datetime IS NOT NULL;
END;
$$ LANGUAGE plpgsql;


