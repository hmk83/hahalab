-- 스케줄 완료 시 활동 로그 및 이력 자동 생성 (YYYYMMDD HH:mm 형식)
CREATE OR REPLACE FUNCTION log_schedule_completion()
RETURNS TRIGGER AS $$
DECLARE
    duration_mins INT;
    start_dt TIMESTAMP;
    end_dt TIMESTAMP;
    start_fmt TEXT;
    end_fmt TEXT;
    now_fmt TEXT;
BEGIN
    -- 현재 시각을 YYYYMMDD HH:mm 형식으로
    now_fmt := TO_CHAR(TIMEZONE('Asia/Seoul', NOW()), 'YYYYMMDD HH24:MI');
    
    IF NEW.status = 'completed' AND OLD.status != 'completed' THEN
        -- 소요 시간 계산
        start_dt := (NEW.date || ' ' || NEW.start_time)::TIMESTAMP;
        end_dt := (NEW.date || ' ' || NEW.end_time)::TIMESTAMP;
        duration_mins := EXTRACT(EPOCH FROM (end_dt - start_dt)) / 60;
        
        -- YYYYMMDD HH:mm 형식으로 변환
        start_fmt := REPLACE(NEW.date, '-', '') || ' ' || NEW.start_time;
        end_fmt := REPLACE(NEW.date, '-', '') || ' ' || NEW.end_time;
        
        -- 활동 로그 생성
        INSERT INTO activity_logs (teacher_name, center_name, type, action, details)
        SELECT 
            t.name,
            t.center,
            CASE WHEN NEW.type = 'reserve' THEN '상담' ELSE '수업' END,
            CASE WHEN NEW.type = 'reserve' THEN '상담완료' ELSE '수업완료' END,
            NEW.client_name || ' (' || start_fmt || ' ~ ' || end_fmt || ')'
        FROM teachers t
        WHERE t.teacher_id = NEW.teacher_id;
        
        -- 이력 생성
        INSERT INTO histories (
            teacher_id, client_id, client_name, 
            type, category, action, 
            event_datetime, start_datetime, end_datetime, duration_minutes, 
            details
        ) VALUES (
            NEW.teacher_id, 
            NEW.client_id, 
            NEW.client_name,
            CASE WHEN NEW.type = 'reserve' THEN 'consultation' ELSE 'session' END,
            CASE WHEN NEW.type = 'reserve' THEN 'consultation_history' ELSE 'session_history' END,
            CASE WHEN NEW.type = 'reserve' THEN '상담완료' ELSE '수업완료' END,
            now_fmt,
            start_fmt,
            end_fmt,
            duration_mins,
            '정상 완료됨'
        );
    END IF;
    
    -- 미출석 처리 시 이력 생성
    IF NEW.status = 'noshow' AND OLD.status != 'noshow' THEN
        start_fmt := REPLACE(NEW.date, '-', '') || ' ' || NEW.start_time;
        
        INSERT INTO histories (
            teacher_id, client_id, client_name, 
            type, category, action, 
            event_datetime, start_datetime, noshow_datetime,
            details
        ) VALUES (
            NEW.teacher_id, 
            NEW.client_id, 
            NEW.client_name,
            'noshow',
            CASE WHEN NEW.type = 'reserve' THEN 'consultation_history' ELSE 'session_history' END,
            '미출석',
            now_fmt,
            start_fmt,
            now_fmt,
            '미출석 처리됨'
        );
    END IF;
    
    -- 일정 변경 시 이력 생성
    IF (NEW.date != OLD.date OR NEW.start_time != OLD.start_time) AND NEW.status != 'deleted' THEN
        start_fmt := REPLACE(OLD.date, '-', '') || ' ' || OLD.start_time;
        end_fmt := REPLACE(NEW.date, '-', '') || ' ' || NEW.start_time;
        
        INSERT INTO histories (
            teacher_id, client_id, client_name, 
            type, category, action, 
            event_datetime, original_datetime, changed_datetime, reschedule_datetime,
            details
        ) VALUES (
            NEW.teacher_id, 
            NEW.client_id, 
            NEW.client_name,
            'reschedule',
            CASE WHEN NEW.type = 'reserve' THEN 'consultation_history' ELSE 'session_history' END,
            '일정변경',
            now_fmt,
            start_fmt,
            end_fmt,
            now_fmt,
            '일정이 변경됨'
        );
    END IF;
    
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trigger_log_schedule_completion ON schedules;
CREATE TRIGGER trigger_log_schedule_completion
    AFTER UPDATE ON schedules
    FOR EACH ROW
    EXECUTE FUNCTION log_schedule_completion();

-- 스케줄 삭제 시 이력 생성 (YYYYMMDD HH:mm 형식)
CREATE OR REPLACE FUNCTION log_schedule_deletion()
RETURNS TRIGGER AS $$
DECLARE
    start_fmt TEXT;
    now_fmt TEXT;
BEGIN
    -- YYYYMMDD HH:mm 형식으로 변환
    start_fmt := REPLACE(OLD.date, '-', '') || ' ' || OLD.start_time;
    now_fmt := TO_CHAR(TIMEZONE('Asia/Seoul', NOW()), 'YYYYMMDD HH24:MI');
    
    INSERT INTO histories (
        teacher_id, client_id, client_name, 
        type, category, action, 
        event_datetime, start_datetime, delete_datetime,
        details
    ) VALUES (
        OLD.teacher_id, 
        OLD.client_id, 
        OLD.client_name,
        'delete',
        CASE WHEN OLD.type = 'reserve' THEN 'consultation_history' ELSE 'session_history' END,
        '일정삭제',
        now_fmt,
        start_fmt,
        now_fmt,
        '스케줄이 삭제됨'
    );
    
    RETURN OLD;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trigger_log_schedule_deletion ON schedules;
CREATE TRIGGER trigger_log_schedule_deletion
    BEFORE DELETE ON schedules
    FOR EACH ROW
    EXECUTE FUNCTION log_schedule_deletion();

-- Notices 테이블 updated_at 자동 갱신 트리거
CREATE OR REPLACE FUNCTION update_notice_timestamp()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = TIMEZONE('utc', NOW());
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

