-- 특정 날짜의 스케줄 조회
CREATE OR REPLACE FUNCTION get_schedules_by_date(p_teacher_id TEXT, p_date TEXT)
RETURNS TABLE (
    id BIGINT,
    client_name TEXT,
    type TEXT,
    start_time TEXT,
    end_time TEXT,
    status TEXT
) AS $$
BEGIN
    RETURN QUERY
    SELECT s.id, s.client_name, s.type, s.start_time, s.end_time, s.status
    FROM schedules s
    WHERE s.teacher_id = p_teacher_id 
    AND s.date = p_date
    AND s.status != 'deleted'
    ORDER BY s.start_time;
END;
$$ LANGUAGE plpgsql;

-- 내담자 통계 조회
CREATE OR REPLACE FUNCTION get_client_stats(p_teacher_id TEXT)
RETURNS TABLE (
    total_clients INT,
    active_clients INT,
    reserve_clients INT,
    paused_clients INT,
    terminated_clients INT
) AS $$
BEGIN
    RETURN QUERY
    SELECT 
        COUNT(*)::INT AS total_clients,
        COUNT(CASE WHEN type = 'client' AND status = 'active' THEN 1 END)::INT AS active_clients,
        COUNT(CASE WHEN type = 'reserve' AND status = 'active' THEN 1 END)::INT AS reserve_clients,
        COUNT(CASE WHEN status = 'paused' THEN 1 END)::INT AS paused_clients,
        COUNT(CASE WHEN status = 'terminated' THEN 1 END)::INT AS terminated_clients
    FROM clients
    WHERE teacher_id = p_teacher_id
    AND status != 'deleted';
END;
$$ LANGUAGE plpgsql;

-- 내담자별 수업 통계 (주간/월간/총) - NEW
CREATE OR REPLACE FUNCTION get_client_session_stats(p_client_id TEXT)
RETURNS TABLE (
    weekly_minutes INT,
    monthly_minutes INT,
    total_minutes INT,
    total_sessions INT
) AS $$
DECLARE
    today DATE := CURRENT_DATE;
    week_start DATE := today - INTERVAL '7 days';
    month_start DATE := today - INTERVAL '30 days';
BEGIN
    RETURN QUERY
    SELECT 
        COALESCE(SUM(CASE WHEN h.date >= week_start::text THEN h.duration_minutes ELSE 0 END), 0)::INT AS weekly_minutes,
        COALESCE(SUM(CASE WHEN h.date >= month_start::text THEN h.duration_minutes ELSE 0 END), 0)::INT AS monthly_minutes,
        COALESCE(SUM(h.duration_minutes), 0)::INT AS total_minutes,
        COUNT(*)::INT AS total_sessions
    FROM histories h
    WHERE h.client_id = p_client_id
    AND h.category = 'session_history'
    AND h.action IN ('수업', '상담')
    AND h.duration_minutes IS NOT NULL;
END;
$$ LANGUAGE plpgsql;


