    occurred_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc', NOW())
);

-- 7. 내담자/예약자 이력 (Histories) 테이블 - ENHANCED
CREATE TABLE IF NOT EXISTS histories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc', NOW()),
    teacher_id TEXT NOT NULL,
    client_id TEXT NOT NULL,
    client_name TEXT NOT NULL,
    type TEXT NOT NULL,              -- 'session', 'consultation', 'noshow', 'reschedule', 'delete'
    category TEXT NOT NULL,          -- 'session_history', 'consultation_history'
    action TEXT NOT NULL,            -- '수업', '상담', '미출석', '일정삭제', '일정변경'
    
    -- 날짜 및 시간 정보
    date TEXT NOT NULL,              -- 일정 날짜 (YYYY-MM-DD)
    start_time TEXT,                 -- 시작 시간 (HH:MM)
    end_time TEXT,                   -- 종료 시간 (HH:MM)
    duration_minutes INT,            -- 총 소요 시간 (분)
    
    -- 일정 변경 정보
    original_date TEXT,              -- 원래 날짜
    changed_date TEXT,               -- 변경된 날짜
    original_time TEXT,              -- 원래 시간
    changed_time TEXT,               -- 변경된 시간
    
    -- 액션 시점 (NEW)
    action_time TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc', NOW()),  -- 미출석처리시점, 삭제시점, 변경시점
    
    details TEXT,
    memo TEXT
);


