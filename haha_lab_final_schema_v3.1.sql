-- 1. 선생님 (Teachers) 테이블
CREATE TABLE IF NOT EXISTS teachers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc', NOW()),
    teacher_id TEXT UNIQUE NOT NULL,
    password TEXT NOT NULL,
    name TEXT NOT NULL,
    center TEXT,
    gender TEXT,
    age INT,
    contact TEXT,
    email TEXT,
    plan TEXT DEFAULT 'Basic Plan',
    status TEXT DEFAULT 'Active',
    memo TEXT,
    registered_clients INT DEFAULT 0
);

-- 2. 내담자 (Clients) 테이블
CREATE TABLE IF NOT EXISTS clients (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc', NOW()),
    teacher_id TEXT NOT NULL,
    name TEXT NOT NULL,
    type TEXT NOT NULL,
    status TEXT DEFAULT 'active',
    gender TEXT,
    dob TEXT,
    age INT,
    contact TEXT,
    address TEXT,
    guardians JSONB,
    session_time INT DEFAULT 50,
    diagnosis TEXT,
    initial_consult TEXT,
    areas JSONB,
    memo TEXT,
    reserve_date TEXT,
    reserve_time TEXT
);

-- 3. 스케줄 (Schedules) 테이블
CREATE TABLE IF NOT EXISTS schedules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc', NOW()),
    teacher_id TEXT NOT NULL,
    client_id TEXT NOT NULL,
    client_name TEXT NOT NULL,
    type TEXT NOT NULL,
    date TEXT NOT NULL,
    start_time TEXT NOT NULL,
    end_time TEXT NOT NULL,
    status TEXT DEFAULT 'scheduled',
    memo TEXT,
    completed_at TIMESTAMP WITH TIME ZONE  -- NEW: 완료 시점 기록
);

-- 4. 공지사항 (Notices) 테이블
CREATE TABLE IF NOT EXISTS notices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc', NOW()),
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc', NOW()),
    type TEXT NOT NULL,
    title TEXT NOT NULL,
    content TEXT,
    date TEXT,
    is_hidden BOOLEAN DEFAULT FALSE
);

-- 5. Play Lab 콘텐츠 (Play Contents) 테이블
CREATE TABLE IF NOT EXISTS play_contents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc', NOW()),
    cat_id TEXT NOT NULL,
    title TEXT NOT NULL,
    url TEXT,
    tags TEXT[],
