-- 스케줄 완료 시 이력 생성 (ENHANCED)
CREATE OR REPLACE FUNCTION log_schedule_completion()
RETURNS TRIGGER AS $$
DECLARE
    duration_mins INT;
    start_datetime TIMESTAMP;
    end_datetime TIMESTAMP;
    action_label TEXT;
BEGIN
    -- 수업/상담 완료 처리
    IF NEW.status = 'completed' AND OLD.status != 'completed' THEN
        start_datetime := (NEW.date || ' ' || NEW.start_time)::TIMESTAMP;
        end_datetime := (NEW.date || ' ' || NEW.end_time)::TIMESTAMP;
        duration_mins := EXTRACT(EPOCH FROM (end_datetime - start_datetime)) / 60;
        
        -- completed_at 자동 설정
        NEW.completed_at := TIMEZONE('utc', NOW());
        
        -- 액션 레이블
        action_label := CASE WHEN NEW.type = 'reserve' THEN '상담' ELSE '수업' END;
        
        -- 활동 로그 생성
        INSERT INTO activity_logs (teacher_name, center_name, type, action, details)
        SELECT 
            t.name,
            t.center,
            CASE WHEN NEW.type = 'reserve' THEN '상담' ELSE '수업' END,
            CASE WHEN NEW.type = 'reserve' THEN '상담완료' ELSE '수업완료' END,
            NEW.client_name || ' (' || NEW.date || ' ' || NEW.start_time || ')'
        FROM teachers t
        WHERE t.teacher_id = NEW.teacher_id;
        
        -- 이력 생성
        INSERT INTO histories (
            teacher_id, client_id, client_name, 
            type, category, action, 
            date, start_time, end_time, duration_minutes,
            action_time, details
        ) VALUES (
            NEW.teacher_id, 
            NEW.client_id, 
            NEW.client_name,
            CASE WHEN NEW.type = 'reserve' THEN 'consultation' ELSE 'session' END,
            CASE WHEN NEW.type = 'reserve' THEN 'consultation_history' ELSE 'session_history' END,
            action_label,
            NEW.date,
            NEW.start_time,
            NEW.end_time,
            duration_mins,
            NEW.completed_at,
            '정상 완료됨'
        );
    END IF;
    
    -- 미출석 처리
    IF NEW.status = 'noshow' AND OLD.status != 'noshow' THEN
        INSERT INTO histories (
            teacher_id, client_id, client_name, 
            type, category, action, 
            date, start_time, end_time,
            action_time, details
        ) VALUES (
            NEW.teacher_id, 
            NEW.client_id, 
            NEW.client_name,
            'noshow',
            CASE WHEN NEW.type = 'reserve' THEN 'consultation_history' ELSE 'session_history' END,
            '미출석',
            NEW.date,
            NEW.start_time,
            NEW.end_time,
            TIMEZONE('utc', NOW()),
            '미출석 처리됨'
        );
    END IF;
    
    -- 일정 변경
    IF (NEW.date != OLD.date OR NEW.start_time != OLD.start_time OR NEW.end_time != OLD.end_time) 
       AND NEW.status != 'deleted' 
       AND OLD.status != 'deleted' THEN
        INSERT INTO histories (
            teacher_id, client_id, client_name, 
            type, category, action, 
            date, start_time, end_time,
            original_date, changed_date,
            original_time, changed_time,
            action_time, details
        ) VALUES (
            NEW.teacher_id, 
            NEW.client_id, 
            NEW.client_name,
            'reschedule',
            CASE WHEN NEW.type = 'reserve' THEN 'consultation_history' ELSE 'session_history' END,
            '일정변경',
            NEW.date,
            NEW.start_time,
            NEW.end_time,
            OLD.date,
            NEW.date,
            OLD.start_time || ' ~ ' || OLD.end_time,
            NEW.start_time || ' ~ ' || NEW.end_time,
            TIMEZONE('utc', NOW()),
            '일정이 변경됨'
        );
    END IF;
    
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trigger_log_schedule_completion ON schedules;
CREATE TRIGGER trigger_log_schedule_completion
    BEFORE UPDATE ON schedules
    FOR EACH ROW
    EXECUTE FUNCTION log_schedule_completion();

-- 스케줄 삭제 시 이력 생성
CREATE OR REPLACE FUNCTION log_schedule_deletion()
RETURNS TRIGGER AS $$
BEGIN
    INSERT INTO histories (
        teacher_id, client_id, client_name, 
        type, category, action, 
        date, start_time, end_time,
        action_time, details
    ) VALUES (
        OLD.teacher_id, 
        OLD.client_id, 
        OLD.client_name,
        'delete',
        CASE WHEN OLD.type = 'reserve' THEN 'consultation_history' ELSE 'session_history' END,
        '일정삭제',
        OLD.date,
        OLD.start_time,
        OLD.end_time,
        TIMEZONE('utc', NOW()),
        '스케줄이 삭제됨'
    );
    
    RETURN OLD;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trigger_log_schedule_deletion ON schedules;
CREATE TRIGGER trigger_log_schedule_deletion
    BEFORE DELETE ON schedules
    FOR EACH ROW
    EXECUTE FUNCTION log_schedule_deletion();

