-- 3.1 Teachers Table
CREATE TABLE teachers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc', NOW()) NOT NULL,
    teacher_id TEXT UNIQUE NOT NULL,
    password TEXT NOT NULL,
    name TEXT NOT NULL,
    center TEXT,
    gender TEXT,
    age INT,
    contact TEXT,
    email TEXT,
    plan TEXT DEFAULT 'Basic Plan',
    status TEXT DEFAULT 'Active',
    memo TEXT,
    registered_clients INT DEFAULT 0
);

-- 3.2 Clients Table
CREATE TABLE clients (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc', NOW()) NOT NULL,
    teacher_id TEXT NOT NULL REFERENCES teachers(teacher_id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    type TEXT NOT NULL CHECK (type IN ('client', 'reserve')),
    status TEXT DEFAULT 'active' CHECK (status IN ('active', 'paused', 'completed')),
    gender TEXT,
    dob TEXT,
    age INT,
    contact TEXT,
    address TEXT,
    guardians JSONB,
    session_time INT DEFAULT 50,
    diagnosis TEXT,
    initial_consult TEXT,
    areas JSONB,
    memo TEXT,
    reserve_date TEXT,
    reserve_time TEXT,
    converted_from_reserve BOOLEAN DEFAULT FALSE,
    original_reserve_id BIGINT
