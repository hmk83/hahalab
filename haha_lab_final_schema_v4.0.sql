-- 8.1 Log Schedule Completion (수업/상담 완료 및 미출석 처리)
CREATE OR REPLACE FUNCTION log_schedule_completion()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_duration INT;
    v_category TEXT;
    v_action TEXT;
    v_datetime TEXT;
BEGIN
    -- 상태가 completed 또는 noshow로 변경되었을 때만 실행
    IF (OLD.status IN ('scheduled') AND NEW.status IN ('completed', 'noshow')) THEN
        
        -- 카테고리 및 액션 결정
        IF NEW.status = 'completed' THEN
            v_category := 'completed';
            v_action := CASE 
                WHEN NEW.type = 'session' THEN '수업 완료'
                WHEN NEW.type = 'consultation' THEN '상담 완료'
            END;
        ELSIF NEW.status = 'noshow' THEN
            v_category := 'noshow';
            v_action := CASE 
                WHEN NEW.type = 'session' THEN '수업 미출석'
                WHEN NEW.type = 'consultation' THEN '상담 미출석'
            END;
        END IF;

        -- 날짜시간 형식: YYYYMMDD HH:mm
        v_datetime := NEW.date || ' ' || NEW.start_time;

        -- 소요 시간 계산 (완료 시에만)
        IF NEW.status = 'completed' THEN
            v_duration := EXTRACT(EPOCH FROM (
                TO_TIMESTAMP(NEW.date || ' ' || NEW.end_time, 'YYYYMMDD HH24:MI') -
                TO_TIMESTAMP(NEW.date || ' ' || NEW.start_time, 'YYYYMMDD HH24:MI')
            ))::INT / 60;
        ELSE
            v_duration := NULL;
        END IF;

        -- Histories 테이블에 기록 추가
        INSERT INTO histories (
            teacher_id,
            client_id,
            client_name,
            type,
            category,
            action,
            event_datetime,
            start_datetime,
            end_datetime,
            noshow_datetime,
            duration_minutes,
            memo,
            schedule_id
        ) VALUES (
            NEW.teacher_id,
            NEW.client_id,
            NEW.client_name,
            NEW.type,
            v_category,
            v_action,
            v_datetime,
            v_datetime,
            CASE WHEN NEW.status = 'completed' THEN NEW.date || ' ' || NEW.end_time ELSE NULL END,
            CASE WHEN NEW.status = 'noshow' THEN v_datetime ELSE NULL END,
            v_duration,
            NEW.memo,
            NEW.id
        );

        -- Activity Logs 테이블에 기록
        INSERT INTO activity_logs (
            teacher_name,
            type,
            action,
            details,
            occurred_at
        )
        SELECT 
            t.name,
            NEW.type,
            v_action,
            '내담자: ' || NEW.client_name || ' | 일시: ' || v_datetime,
            TIMEZONE('utc', NOW())
        FROM teachers t
        WHERE t.teacher_id = NEW.teacher_id;

        -- completed_at 타임스탬프 업데이트
        NEW.completed_at := TIMEZONE('utc', NOW());
    END IF;

    RETURN NEW;
END;
$$;

-- 8.2 Log Schedule Deletion (일정 삭제 시)
CREATE OR REPLACE FUNCTION log_schedule_deletion()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_datetime TEXT;
    v_action TEXT;
BEGIN
    -- 캘린더에서만 삭제된 경우 (is_visible_in_calendar = FALSE)는 기록하지 않음
    IF OLD.is_visible_in_calendar = FALSE THEN
        RETURN OLD;
    END IF;

    -- 날짜시간 형식: YYYYMMDD HH:mm
    v_datetime := OLD.date || ' ' || OLD.start_time;
    
    v_action := CASE 
        WHEN OLD.type = 'session' THEN '수업 일정 삭제'
        WHEN OLD.type = 'consultation' THEN '상담 일정 삭제'
    END;

    -- Histories 테이블에 삭제 기록
    INSERT INTO histories (
        teacher_id,
        client_id,
        client_name,
        type,
        category,
        action,
        event_datetime,
        delete_datetime,
        memo,
        schedule_id
    ) VALUES (
        OLD.teacher_id,
        OLD.client_id,
        OLD.client_name,
        OLD.type,
        'deleted',
        v_action,
        v_datetime,
        v_datetime,
        OLD.memo,
        OLD.id
    );

    -- Activity Logs 테이블에 기록
    INSERT INTO activity_logs (
        teacher_name,
        type,
        action,
        details,
        occurred_at
    )
    SELECT 
        t.name,
        OLD.type,
        v_action,
        '내담자: ' || OLD.client_name || ' | 일시: ' || v_datetime,
        TIMEZONE('utc', NOW())
    FROM teachers t
    WHERE t.teacher_id = OLD.teacher_id;

    RETURN OLD;
END;
$$;

