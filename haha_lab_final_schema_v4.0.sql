-- 7.1 Get Schedules by Date
CREATE OR REPLACE FUNCTION get_schedules_by_date(
    p_teacher_id TEXT,
    p_date TEXT
)
RETURNS TABLE (
    id BIGINT,
    created_at TIMESTAMP WITH TIME ZONE,
    teacher_id TEXT,
    client_id TEXT,
    client_name TEXT,
    type TEXT,
    date TEXT,
    start_time TEXT,
    end_time TEXT,
    status TEXT,
    memo TEXT,
    completed_at TIMESTAMP WITH TIME ZONE,
    is_visible_in_calendar BOOLEAN
)
LANGUAGE plpgsql
AS $$
BEGIN
    RETURN QUERY
    SELECT 
        s.id,
        s.created_at,
        s.teacher_id,
        s.client_id,
        s.client_name,
        s.type,
        s.date,
        s.start_time,
        s.end_time,
        s.status,
        s.memo,
        s.completed_at,
        s.is_visible_in_calendar
    FROM schedules s
    WHERE s.teacher_id = p_teacher_id
      AND s.date = p_date
      AND s.is_visible_in_calendar = TRUE
    ORDER BY s.start_time;
END;
$$;

-- 7.2 Get Client Statistics
CREATE OR REPLACE FUNCTION get_client_stats(p_teacher_id TEXT)
RETURNS TABLE (
    total_clients BIGINT,
    active_clients BIGINT,
    reserve_clients BIGINT,
    paused_clients BIGINT,
    completed_clients BIGINT
)
LANGUAGE plpgsql
AS $$
BEGIN
    RETURN QUERY
    SELECT
        COUNT(*) AS total_clients,
        COUNT(*) FILTER (WHERE type = 'client' AND status = 'active') AS active_clients,
        COUNT(*) FILTER (WHERE type = 'reserve') AS reserve_clients,
        COUNT(*) FILTER (WHERE status = 'paused') AS paused_clients,
        COUNT(*) FILTER (WHERE status = 'completed') AS completed_clients
    FROM clients
    WHERE teacher_id = p_teacher_id;
END;
$$;

-- 7.3 Get Session Time Statistics (통합: 수업 + 상담)
CREATE OR REPLACE FUNCTION get_session_time_stats(p_client_id TEXT)
RETURNS TABLE (
    weekly_minutes INT,
    monthly_minutes INT,
    total_minutes INT,
    total_sessions BIGINT
)
LANGUAGE plpgsql
AS $$
DECLARE
    v_today TEXT;
    v_week_start TEXT;
    v_month_start TEXT;
BEGIN
    v_today := TO_CHAR(CURRENT_DATE, 'YYYYMMDD');
    v_week_start := TO_CHAR(CURRENT_DATE - INTERVAL '7 days', 'YYYYMMDD');
    v_month_start := TO_CHAR(CURRENT_DATE - INTERVAL '30 days', 'YYYYMMDD');

    RETURN QUERY
    SELECT
        COALESCE(SUM(duration_minutes) FILTER (
            WHERE start_datetime >= v_week_start 
            AND start_datetime <= v_today
            AND category = 'completed'
        ), 0)::INT AS weekly_minutes,
        COALESCE(SUM(duration_minutes) FILTER (
            WHERE start_datetime >= v_month_start 
            AND start_datetime <= v_today
            AND category = 'completed'
        ), 0)::INT AS monthly_minutes,
        COALESCE(SUM(duration_minutes) FILTER (
            WHERE category = 'completed'
        ), 0)::INT AS total_minutes,
        COUNT(*) FILTER (WHERE category = 'completed') AS total_sessions
    FROM histories
    WHERE client_id = p_client_id;
END;
$$;

